def map_answer(grid, x, y, z, z2=None, radius=10, plots=(), day=0):
    """The /query/map answer for a box of `radius` around x,y on levels z..z2 from GRIDS[grid]."""
    x1, x2, y1, y2 = x - radius, x + radius, y - radius, y + radius
    levels = []
    lo, hi = (min(z, z2), max(z, z2)) if isinstance(z2, int) else (z, z)
    for lz in range(hi, lo - 1, -1):
        gx, gy, rows = GRIDS[grid].get(lz, (0, 0, []))
        shape = []
        for ty in range(y1, y2 + 1):
            row = rows[ty - gy] if 0 <= ty - gy < len(rows) else ""
            shape.append("".join(row[tx - gx] if 0 <= tx - gx < len(row) else "?" for tx in range(x1, x2 + 1)))
        levels.append({"z": lz, "shape": shape, "light": [r.replace(".", "u") for r in shape], "material": shape})
    buildings = [{"built": True, "id": 500 + i, "type": "FarmPlot", "x1": p["x"], "x2": p["x"] + (p.get("w") or 3) - 1,
                  "y1": p["y"], "y2": p["y"] + (p.get("h") or 3) - 1, "z": p["z"]}
                 for i, p in enumerate(plots) if lo <= p.get("z", -1) <= hi]
    return {"day": day, "query": "map", "result": {
        "ok": True, "x1": x1, "x2": x2, "y1": y1, "y2": y2, "levels": levels, "buildings": buildings,
        "designations": [], "liquid": [], "rows": "levels[].shape[i] is the row y = y1 + i, character j is x = x1 + j"}}


class MapQueries:
    """A fake game's query(): "map" answers from GRIDS[self.grid] (the observation's plots in self.plots), others
    fall back to the base fake's own."""
    grid = None
    plots = ()

    def query(self, name, **kw):
        if name == "map" and self.grid is not None:
            self.map_queries = getattr(self, "map_queries", 0) + 1
            return map_answer(self.grid, kw["x"], kw["y"], kw["z"], kw.get("z2"), kw.get("radius", 10),
                              plots=self.plots)
        return super().query(name, **kw)
